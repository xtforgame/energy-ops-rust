/**
 * 墨刷全域參數（對應 demo 調墨面板的四個滑桿；編輯器「匯出」的 params 區塊貼回這裡）。
 * 逐筆的顏色 / 筆寬 / 路徑仍在上面的 logoStrokes 裡。
 */
export interface LogoInkParams {
  /** 墨量 0..1：越低飛白越多 */
  ink: number;
  /** 毛數倍率 */
  bristle: number;
  /** 全域筆寬倍率（乘在每筆的 width 上） */
  widthScale: number;
  /**
   * 餘韻（ms）：一個點從畫上到消失的壽命。null = 自動（drawMs + holdMs）。
   *
   * ⚠️ 定案值 1000ms 讓墨的完整流程（畫上 ~378ms + 餘韻 1000ms ≈ 1.38s）**長於
   * 900ms 的轉場**。這是刻意的：墨從轉場第 0ms 就開始播、能播多少算多少 ——
   * 實際效果是畫上 → 停住 → 跟著雲的收尾一起淡出（尾巴不會自己離場）。
   */
  lifeMs: number | null;
}

