type Dict = { [k: string]: string | Dict };

/** 深合併（右邊蓋左邊），只處理純物件。 */
export function mergeMessages<T extends object>(base: T, extra: Dict): T {
  const out: any = { ...base };
  for (const [k, v] of Object.entries(extra)) {
    out[k] = v && typeof v === 'object' && out[k] && typeof out[k] === 'object' ? mergeMessages(out[k], v) : v;
  }
  return out;
}

